#!/bin/sh
# Caddy gateway: public HTTPS for one domain, round-robin over the processors' VPC IPs.
# No Docker, no API key, no Arachnid credentials on this machine.
set -eu
umask 022
HERE=$(CDPATH='' cd -- "$(dirname -- "$0")" && pwd)
. "$HERE/../lib/common.sh"
require_root
require_alpine
require_tty

ETC=/etc/swoovr-caddy
BACKEND_PORT=8080

heading 'Caddy gateway'
info 'All answers are collected before anything on this VM is changed.' ''

ask DOMAIN 'Public DNS hostname for HTTPS (e.g. images.example.com)'
case "$DOMAIN" in ''|*' '*|*/*|*:*|*@*|*_*|*..*|.*|*.) die "Invalid hostname: $DOMAIN";; esac
printf '%s' "$DOMAIN" | grep -Eq '^[A-Za-z0-9][A-Za-z0-9.-]*\.[A-Za-z][A-Za-z0-9-]*$' ||
    die 'Expected a public DNS hostname, not an IP address.'

info '' "Processor VPC IPv4 addresses (port $BACKEND_PORT). Enter one per line, blank line to finish."
BACKENDS=''
n=1
while :; do
    ask ip "  Backend #$n"
    [ -n "$ip" ] || { [ -n "$BACKENDS" ] && break; warn 'At least one backend is required.'; continue; }
    valid_ipv4 "$ip" || { warn "Not a valid IPv4 address: $ip"; continue; }
    is_private_ipv4 "$ip" || { warn 'Use the processor VPC (private) address, not a public IP.'; continue; }
    case " $BACKENDS " in *" $ip "*) warn "$ip already entered."; continue;; esac
    route=$(ip -4 route get "$ip" 2>/dev/null) || { warn "No route to $ip from this VM; is the VPC attached?"; continue; }
    info "    route: $route"
    case "$route" in
        *' via '*) confirm "    $ip is reached via a gateway, not directly on the VPC link. Typo? Use it anyway?" || continue;;
    esac
    BACKENDS="$BACKENDS $ip"
    n=$((n + 1))
done
BACKENDS=${BACKENDS# }

info '' 'Summary' \
    "  HTTPS domain:  $DOMAIN  (public TCP 80/443)" \
    "  Round-robin:   $BACKENDS  (port $BACKEND_PORT)" \
    '  SSH:           TCP 22 open to any source' ''
confirm 'Install now?' || die 'Cancelled.'

heading 'Packages'
ensure_community_repo
apk update
apk add caddy caddy-openrc ufw curl ca-certificates

heading 'Configuration'
mkdir -p "$ETC" /etc/caddy
chmod 755 "$ETC"
printf 'DOMAIN=%s\nBACKEND_PORT=%s\n' "$DOMAIN" "$BACKEND_PORT" > "$ETC/gateway.env"
chmod 644 "$ETC/gateway.env"
# shellcheck disable=SC2086  # intentional split: one validated IPv4 per line
printf '%s\n' $BACKENDS > "$ETC/backends"
chmod 644 "$ETC/backends"
install -m 755 "$HERE/swoovr-backend" /usr/local/sbin/swoovr-backend
install -m 755 "$HERE/swoovr-gateway-test" /usr/local/sbin/swoovr-gateway-test
if [ -f /etc/caddy/Caddyfile ] && ! grep -q 'Generated by swoovr-backend' /etc/caddy/Caddyfile; then
    cp -p /etc/caddy/Caddyfile "/etc/caddy/Caddyfile.before-swoovr-$(date +%Y%m%d%H%M%S)"
fi
swoovr-backend render --no-reload

heading 'Firewall'
rc-update add ufw default >/dev/null 2>&1 || true
ufw default deny incoming
ufw default allow outgoing
ufw default deny routed
ufw allow 22/tcp
ufw allow 80/tcp
ufw allow 443/tcp
ufw --force enable
ufw status verbose

heading 'Caddy service'
rc-update add caddy default >/dev/null 2>&1 || true
rc-service caddy restart || rc-service caddy start

heading 'Backends'
swoovr-backend list
for ip in $BACKENDS; do
    code=$(curl -s -o /dev/null -w '%{http_code}' --connect-timeout 5 --max-time 15 "http://$ip:$BACKEND_PORT/ready" || true)
    [ "$code" = 200 ] || warn "$ip is not ready yet (HTTP ${code:-000}). Caddy will route to it once /ready returns 200."
done

info '' 'Installed.' \
    "  Point the DNS A record for $DOMAIN at this VM's public IPv4 (Caddy then obtains the certificate)." \
    '  Test:          swoovr-gateway-test' \
    '  Manage pool:   swoovr-backend list | add <ip> | remove <ip> | replace <old> <new>'
